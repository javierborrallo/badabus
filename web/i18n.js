let idiomaActual = detectarIdioma();

function detectarIdioma() {
  try {
    const g = localStorage.getItem("idioma");
    if (g === "es" || g === "en") return g;
  } catch {
    /* ignore */
  }
  const nav = String(navigator.language || "es").toLowerCase();
  return nav.startsWith("en") ? "en" : "es";
}

export function idioma() {
  return idiomaActual;
}

export function fijarIdioma(nuevo) {
  idiomaActual = nuevo === "en" ? "en" : "es";
  document.documentElement.lang = idiomaActual;
  try {
    localStorage.setItem("idioma", idiomaActual);
  } catch {
    /* ignore */
  }
  return idiomaActual;
}

export function t(clave, params = {}) {
  const dic = TEXTOS[idiomaActual] || TEXTOS.es;
  let texto = dic[clave] ?? TEXTOS.es[clave] ?? clave;
  for (const [k, v] of Object.entries(params)) {
    texto = texto.replaceAll(`{${k}}`, String(v));
  }
  return texto;
}

export function etiquetaDia(tipoDia) {
  if (tipoDia === "SAB") return t("dia_sab");
  if (tipoDia === "DOM") return t("dia_dom");
  return t("dia_lv");
}
